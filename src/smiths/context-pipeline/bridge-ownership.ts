// Migrate startup ownership without nesting markers or discarding operator text.
import { buildRuleStartupBootstrapBlock } from './workspace-bootstrap.js';
export const AGENTS_HEADER = '# AGENTS.md\n<!-- aiwg-managed -->\n<!-- Generated by AIWG. Edit AGENTS.override.md for operator additions. -->\n';
const bootstrapBlock = /<!-- AIWG:provider-bootstrap:start -->[\s\S]*?<!-- AIWG:provider-bootstrap:end -->/g;
export const hasRuleStartup = (content: string): boolean => /<!-- AIWG:rule-hook-[\w-]+:start -->/.test(content);

export function retireLegacyBridge(content: string): string {
  return content.replace(/\n\n---\n\n<!-- BEGIN AIWG-managed \(auto-generated;[^\n]*-->[\s\S]*?<!-- END AIWG-managed -->\n?/g, '\n')
    .replace(/<!-- BEGIN AIWG-managed \(auto-generated;[^\n]*-->[\s\S]*?<!-- END AIWG-managed -->\n?/g, '');
}

export function normalizeRuleStartup(content: string, bootstrap: string, agentsHeader = false, retireLegacy = true): string {
  if (retireLegacy) content = retireLegacyBridge(content);
  // Retire context-hook's generated body; retain agents-md's enclosed content.
  content = content.replace(/<!-- AIWG:context-hook:start -->[\s\S]*?<!-- AIWG:context-hook:end -->\r?\n?/g, '')
    .replace(/<!-- AIWG:agents-md:(?:start|end) -->\r?\n?/g, '')
    .replace(/\n## For Hermes Sessions\n\nHermes does not auto-load AIWG\.md\. Browse AIWG capabilities with:\n\n- `artifact-read AIWG\.md` through AIWG MCP\.\n- `aiwg discover "<intent>"` and `aiwg show <type> <name>`\.\n- `delegate_task` through the AIWG-orchestrate skill\.\n/, '');
  if (retireLegacy) content = content.replace(/## Framework Context\r?\n[\s\S]*?\*See `AGENTS.override.md` for operator-authored additions\.\*\r?\n?/g, '');
  if (content.includes('<!-- AIWG:rule-core:start -->')) {
    content = content.replace(/<!-- AIWG:core-rules:(?:start|end) -->\r?\n?/g, '');
  }
  let installed = false;
  content = content.replace(bootstrapBlock, () => {
    if (installed) return '';
    installed = true;
    return bootstrap;
  });
  if (!installed) content = `${content}${content.endsWith('\n') ? '\n' : '\n\n'}${bootstrap}\n`;
  if (agentsHeader && !content.startsWith(AGENTS_HEADER)) {
    content = content.replace(/^# AGENTS\.md\r?\n/gm, '')
      .replace(/^<!-- (?:aiwg-managed|Generated by AIWG\.[^\n]*) -->\r?\n?/gm, '');
    // Round 3 left the old generated Framework Context separator at the top.
    content = content.replace(/^(?:[ \t]*\r?\n)*---[ \t]*\r?\n/, '').replace(/^\s+/, '');
    content = `${AGENTS_HEADER}\n${content}`;
  }
  return content;
}

export function preserveBridgeOperatorText(existing: string, generated: string): string {
  if (!generated.startsWith(AGENTS_HEADER) || !existing) return generated;
  const fallback = generated.match(bootstrapBlock)?.[0];
  if (!fallback) return generated;
  // Refresh the shared rule-deployment bootstrap too; retain core and harness
  // hooks independently rather than preserving obsolete startup instructions.
  const bootstrap = hasRuleStartup(existing) ? buildRuleStartupBootstrapBlock() : fallback;
  return normalizeRuleStartup(existing, bootstrap, true);
}
