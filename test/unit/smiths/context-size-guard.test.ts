import { describe, it, expect, beforeEach, afterEach } from 'vitest';
import { promises as fs } from 'node:fs';
import * as path from 'node:path';
import * as os from 'node:os';
import { execFileWithCapture as execFileSync } from '../../helpers/exec-file-capture.js';
import { parseRuleFrontmatter, readCoreBody } from '../../../src/rules/activation.mjs';
import { generate, AGENTS_MD_PROVIDERS } from '../../../src/smiths/context-pipeline/index.js';
import { readRuleDeliveryContext } from '../../helpers/rule-delivery-context.js';
import { listProviderDefinitions } from '../../../src/providers/provider-definitions.js';

const {
  scanContextBridgeSizes,
  formatContextBridgeSizeReport,
  DEFAULT_BRIDGE_CEILING_BYTES,
} = await import('../../../tools/lint/context-size-guard.mjs');

let tmpDir: string;

beforeEach(async () => {
  tmpDir = await fs.mkdtemp(path.join(os.tmpdir(), 'aiwg-context-size-'));
});

// Regeneration preserves independently owned compact core and harness hooks.
const contracts = [
  '<!-- AIWG:rule-core:start -->',
  '## Core rules', 'Finish the authorized task and verify results before claiming completion.',
  '<!-- AIWG:rule-core:end -->',
  '<!-- AIWG:rule-hook-codex:start -->',
  'codex: Before every task and subagent task, read and follow `.codex/rules/RULES-INDEX.md`.',
  '<!-- AIWG:rule-hook-codex:end -->',
].join('\n');

describe('generated bridges with full configuration', () => {
  it('reports full Flue context separately and retains the bridge limit for all other bytes', async () => {
    const payload = '<!-- AIWG:flue-context:start -->\n# Flue AIWG context (experimental)\n' + 'context '.repeat(2048) + '\n<!-- AIWG:flue-context:end -->';
    const bridge = 'Operator policy.\n';
    const file = path.join(tmpDir, 'AGENTS.md');
    await fs.writeFile(file, bridge + payload);
    const scan = await scanContextBridgeSizes({ rootDir: tmpDir });
    expect(scan.violations).toEqual([]);
    expect(scan.records[0]).toMatchObject({ size: Buffer.byteLength(bridge), inlineBytes: Buffer.byteLength(payload) });
    expect(formatContextBridgeSizeReport(scan)).toContain('inline Flue context:');
    expect(await fs.readFile(file, 'utf8')).toBe(bridge + payload);
    await fs.writeFile(file, bridge + payload.replace('<!-- AIWG:flue-context:end -->', ''));
    expect((await scanContextBridgeSizes({ rootDir: tmpDir })).violations).toHaveLength(1);
    await fs.writeFile(file, 'operator '.repeat(2048) + payload);
    expect((await scanContextBridgeSizes({ rootDir: tmpDir })).violations).toHaveLength(1);
  });

  it.each(['fresh', 'legacy', 'round3'])('keeps one flat bootstrap and canonical header across two full deployments from %s', async initial => {
    const repo = path.resolve(__dirname, '../../..');
    const project = path.join(tmpDir, 'project'), home = path.join(tmpDir, 'home');
    const configDir = path.join(home, 'config');
    await fs.mkdir(path.join(project, '.aiwg'), { recursive: true });
    await fs.mkdir(configDir, { recursive: true });
    await fs.copyFile(path.join(repo, 'test/fixtures/context/full-provider.aiwg.config'), path.join(project, '.aiwg/aiwg.config'));
    await fs.writeFile(path.join(configDir, 'channel.json'), JSON.stringify({ channel: 'edge', edgePath: repo, devMode: true, checkOnStartup: false }));
    const bridgePath = path.join(project, 'AGENTS.md');
    const operator = '\n## Operator notes\nKeep this literal separator:\n\n---\n\nAnd these instructions.\n';
    if (initial !== 'fresh') {
      const original = initial === 'legacy'
        ? await fs.readFile(path.join(repo, 'test/fixtures/context/legacy-AGENTS.md'), 'utf8')
        : await fs.readFile(path.join(repo, 'test/fixtures/context/round3-AGENTS.md'), 'utf8');
      await fs.writeFile(bridgePath, original.replace('<!-- AIWG:provider-bootstrap:start -->', operator + '<!-- AIWG:provider-bootstrap:start -->') + operator);
    }
    const env = { PATH: process.env.PATH, CI: '1', HOME: home, USERPROFILE: home,
      HERMES_HOME: path.join(home, '.hermes'), AIWG_CONFIG: configDir,
      AIWG_ARTIFACTS_PATH: path.join(tmpDir, 'artifacts'),
      XDG_DATA_HOME: path.join(home, 'data'), XDG_CONFIG_HOME: configDir,
      XDG_CACHE_HOME: path.join(home, 'cache'), XDG_STATE_HOME: path.join(home, 'state') };
    const deploy = () => execFileSync(process.execPath, [path.join(repo, 'bin/aiwg.mjs'), 'use', 'all'], {
      cwd: project, env, encoding: 'utf8', timeout: 240_000, stdio: 'pipe',
    });
    deploy();
    const first = await fs.readFile(bridgePath, 'utf8');
    expect.soft(first.match(/<!-- AIWG:provider-bootstrap:start -->/g), 'single bootstrap').toHaveLength(1);
    let depth = 0;
    for (const marker of first.matchAll(/<!-- AIWG:[\w-]+:(start|end) -->/g)) {
      depth += marker[1] === 'start' ? 1 : -1;
      expect.soft(depth, `flat markers: ${marker[0]}`).toBe(marker[1] === 'start' ? 1 : 0);
    }
    expect.soft(first.startsWith('# AGENTS.md\n<!-- aiwg-managed -->\n<!-- Generated by AIWG. Edit AGENTS.override.md for operator additions. -->\n'), 'canonical header without separator').toBe(true);
    expect.soft(first).toContain('WORKSPACE.md');
    expect.soft(first.indexOf('WORKSPACE.md')).toBeLessThan(first.indexOf('AIWG.md'));
    expect.soft(first).toContain('Plain Markdown links are not claimed to auto-load');
    expect.soft(first).toContain('AIWG rules deployed to this project are binding');
    if (initial !== 'fresh') expect.soft(first.split(operator)).toHaveLength(3);
    deploy();
    expect.soft(await fs.readFile(bridgePath, 'utf8'), 'byte-identical redeployment').toBe(first);
  }, 600_000);

  it.each([...AGENTS_MD_PROVIDERS])('%s retains binding contracts with at least 5%% bridge headroom', async provider => {
    const providers = listProviderDefinitions().map(definition => definition.id);
    const frameworks = ['all', 'sdlc-complete', 'research-complete', 'forensics-complete',
      'ops-complete', 'security-engineering', 'knowledge-base', 'media-marketing-kit',
      'media-curator', 'validation-complete'];
    await fs.mkdir(path.join(tmpDir, '.aiwg'));
    await fs.writeFile(path.join(tmpDir, '.aiwg/aiwg.config'), JSON.stringify({
      version: '1', providers,
      installed: Object.fromEntries(frameworks.map(name => [name, {
        version: '1.0.0', source: 'bundled', installedAt: '2026-01-01T00:00:00.000Z',
        deployedTo: Object.fromEntries(providers.map(id => [id, { agents: 1, skills: 1, rules: 1, commands: 0 }])),
      }])),
      remotes: { primary: 'origin', issue_tracker: 'origin', issue_provider: 'gitea', ci: 'origin', secondary: [] },
    }));
    await fs.writeFile(path.join(tmpDir, 'AGENTS.md'), `<!-- aiwg-managed -->\n${contracts}\n`);
    const options = {
      projectPath: tmpDir, provider, detectExistingFiles: true,
      sections: [{ type: 'skills' as const, entries: Array.from({ length: 500 }, (_, i) => ({
        id: `fixture-skill-${i}`, description: 'A full installation capability.',
        path: `.agents/skills/fixture-skill-${i}/SKILL.md`,
      })) }],
    };
    const result = await generate(options);
    expect(result.agentsMdPath).toBe(path.join(tmpDir, 'AGENTS.md'));
    const scan = await scanContextBridgeSizes({ rootDir: tmpDir });
    expect(scan.ceilingBytes).toBe(DEFAULT_BRIDGE_CEILING_BYTES);
    expect(scan.violations).toEqual([]);
    for (const record of scan.records.filter((entry: { exists: boolean }) => entry.exists)) {
      expect(record.size).toBeLessThanOrEqual(Math.floor(DEFAULT_BRIDGE_CEILING_BYTES * 0.95));
    }
    const bridge = await fs.readFile(result.agentsMdPath, 'utf8');
    expect(result.agentsMdBytes).toBe(Buffer.byteLength(bridge, 'utf8'));
    expect(bridge).toContain('AIWG rules deployed to this project are binding');
    expect(bridge).toContain('Platform capability and safety constraints remain absolute');
    for (const contract of contracts.split('\n')) expect(bridge).toContain(contract);
    const companion = await fs.readFile(result.aiwgMdPath, 'utf8');
    expect(companion).not.toContain('AIWG:rule-hook-codex:start');
    expect(companion).toContain('Do not add AIWG attribution');
    expect(companion).toContain('Project config decides tracker authority');
    expect(companion).toContain('Internal/canonical tracker: `origin`');
    // Repeated regeneration keeps the exact startup contract inline once.
    await generate(options);
    expect(await fs.readFile(result.agentsMdPath, 'utf8')).toBe(bridge);
    expect(bridge.match(/AIWG:rule-hook-codex:start/g)).toHaveLength(1);
  });

  it('fits this repository’s complete provider configuration in 4 KB with every kernel body in each harness rules surface', async () => {
    const repo = path.resolve(__dirname, '../../..');
    const project = path.join(tmpDir, 'project');
    const home = path.join(tmpDir, 'home');
    const configDir = path.join(home, 'config');
    await fs.mkdir(path.join(project, '.aiwg'), { recursive: true });
    await fs.mkdir(configDir, { recursive: true });
    // A committed fixture with this repository's provider set: .aiwg/aiwg.config is local-only and absent in CI.
    const config = JSON.parse(await fs.readFile(path.join(repo, 'test/fixtures/context/full-provider.aiwg.config'), 'utf8'));
    await fs.writeFile(path.join(project, '.aiwg/aiwg.config'), JSON.stringify(config));
    await fs.writeFile(path.join(configDir, 'channel.json'), JSON.stringify({
      channel: 'edge', edgePath: repo, devMode: true, checkOnStartup: false,
    }));
    // Exercise migration from the existing wholly generated provider template too.
    await fs.writeFile(path.join(project, 'AGENTS.md'), 'Operator text before.\n<!-- BEGIN AIWG-managed (auto-generated; legacy bridge) -->\n' + 'old generated context '.repeat(1000) + '\n<!-- END AIWG-managed -->\n<!-- AIWG:rule-startup:start -->\nSTALE_INLINE_KERNEL\n<!-- AIWG:rule-startup:end -->\nOperator text after.\n');
    const env = { PATH: process.env.PATH, CI: '1', HOME: home, USERPROFILE: home,
      HERMES_HOME: path.join(home, '.hermes'), AIWG_CONFIG: configDir,
      AIWG_ARTIFACTS_PATH: path.join(tmpDir, 'artifacts'),
      XDG_DATA_HOME: path.join(home, 'data'), XDG_CONFIG_HOME: configDir,
      XDG_CACHE_HOME: path.join(home, 'cache'), XDG_STATE_HOME: path.join(home, 'state') };
    execFileSync(process.execPath, [path.join(repo, 'bin/aiwg.mjs'), 'use', 'all'], {
      cwd: project, env, encoding: 'utf8', timeout: 240_000, stdio: 'pipe',
    });
    const bridgePath = path.join(project, 'AGENTS.md');
    const bridge = await fs.readFile(bridgePath, 'utf8');
    const scan = await scanContextBridgeSizes({ rootDir: project });
    expect(scan.violations).toEqual([]);
    expect(Buffer.byteLength(bridge)).toBeLessThanOrEqual(4096);
    expect(bridge).toContain('Operator text before.');
    expect(bridge).toContain('Operator text after.');
    expect(bridge).not.toContain('STALE_INLINE_KERNEL');
    const canonicalDir = path.join(repo, 'agentic/code/addons/aiwg-utils/rules');
    const canonicalKernels: string[] = [];
    for (const name of await fs.readdir(canonicalDir)) {
      if (!name.endsWith('.md') || name.endsWith('.core.md')) continue;
      if (parseRuleFrontmatter(await fs.readFile(path.join(canonicalDir, name), 'utf8')).rule?.activation === 'kernel') canonicalKernels.push(name);
    }
    expect(canonicalKernels.length).toBeGreaterThan(0);
    let kernels = 0;
    for (const provider of config.providers) {
      const rulesDir = path.join(project, `.${provider}/rules`);
      const receipt = JSON.parse(await fs.readFile(path.join(rulesDir, '.aiwg-manifest.json'), 'utf8'));
      for (const name of canonicalKernels) {
        expect(Object.keys(receipt.managed), `${provider}: managed kernel ${name}`).toContain(name);
        expect(receipt.ruleSources.map((file: string) => path.basename(file)), `${provider}: selected kernel ${name}`).toContain(name);
      }
      const files = Object.keys(receipt.managed).map(file => ({ path: path.join(rulesDir, file) }));
      readRuleDeliveryContext({ contributors: files }, provider);
      for (const file of receipt.ruleSources) {
        const parsed = parseRuleFrontmatter(await fs.readFile(file, 'utf8'));
        if (parsed.rule?.activation === 'kernel') kernels++;
        if (parsed.rule?.activation === 'core' && provider !== 'claude') expect(bridge).toContain(readCoreBody(file));
      }
      if (provider !== 'claude') expect(bridge).toContain(`${provider}: Before every task and subagent task, read and follow \`.${provider}/rules/RULES-INDEX.md\``);
    }
    expect(kernels).toBeGreaterThan(0);
    const lint = execFileSync('npm', ['run', 'lint:context-sizes', '--', '--root', project], {
      cwd: repo, env, encoding: 'utf8', timeout: 60_000, stdio: 'pipe',
    });
    expect(lint).toContain('AGENTS.md:');
    expect(bridge).toContain('AIWG rules deployed to this project are binding');
    expect(bridge).not.toContain('Bridge rule contracts');
    console.info(`Full-config AGENTS.md: ${Buffer.byteLength(bridge)} bytes; ${kernels} kernel bodies verified across all deployed harnesses.`);
  }, 300_000);

  it('preserves an operator-owned companion and compact startup hooks', async () => {
    const operator = '# Operator framework notes\nKeep this byte-for-byte.\n';
    await fs.writeFile(path.join(tmpDir, 'AIWG.md'), operator);
    await fs.writeFile(path.join(tmpDir, 'AGENTS.md'), `<!-- aiwg-managed -->\n${contracts}\n`);
    await generate({ projectPath: tmpDir, provider: 'codex', sections: [], detectExistingFiles: true });
    expect(await fs.readFile(path.join(tmpDir, 'AIWG.md'), 'utf8')).toBe(operator);
    expect(await fs.readFile(path.join(tmpDir, 'AGENTS.md'), 'utf8')).toContain('AIWG:rule-hook-codex:start');
  });

  it('keeps compact core and hooks when companion generation is explicitly disabled', async () => {
    await fs.writeFile(path.join(tmpDir, 'AGENTS.md'), `<!-- aiwg-managed -->\n${contracts}\n`);
    await generate({ projectPath: tmpDir, provider: 'codex', sections: [], skip: { aiwgMd: true } });
    expect(await fs.readFile(path.join(tmpDir, 'AGENTS.md'), 'utf8')).toContain('AIWG:rule-hook-codex:start');
    await expect(fs.access(path.join(tmpDir, 'AIWG.md'))).rejects.toThrow();
  });

  it.each(['', 'Preserve these operator notes.\n'])('recognizes template ownership without losing operator text (%j)', async operator => {
    const template = '<!-- BEGIN AIWG-managed (auto-generated; edits between these markers are overwritten on redeploy) -->\n# Provider template\n<!-- END AIWG-managed -->';
    await fs.writeFile(path.join(tmpDir, 'AGENTS.md'), `${operator}${template}\n${contracts}\n`);
    await generate({ projectPath: tmpDir, provider: 'codex', sections: [], detectExistingFiles: true });
    const bridge = await fs.readFile(path.join(tmpDir, 'AGENTS.md'), 'utf8');
    if (operator) {
      expect(bridge.startsWith(operator + template)).toBe(true);
      for (const contract of contracts.split('\n')) expect(bridge).toContain(contract);
    } else {
      expect(bridge).not.toContain('Provider template');
      expect(Buffer.byteLength(bridge)).toBeLessThanOrEqual(Math.floor(DEFAULT_BRIDGE_CEILING_BYTES * 0.95));
      for (const contract of contracts.split('\n')) expect(bridge).toContain(contract);
    }
  });
});

afterEach(async () => {
  await fs.rm(tmpDir, { recursive: true, force: true });
});

describe('context-size guard', () => {
  it('distinguishes missing bridges from existing files at the ceiling', async () => {
    await fs.writeFile(path.join(tmpDir, 'AGENTS.md'), 'x'.repeat(64), 'utf8');

    const result = await scanContextBridgeSizes({
      rootDir: tmpDir,
      ceilingBytes: 64,
      files: ['AGENTS.md', 'WARP.md'],
    });

    expect(result.records).toEqual([
      { path: 'AGENTS.md', exists: true, size: 64, ceilingBytes: 64 },
      { path: 'WARP.md', exists: false, size: 0, ceilingBytes: 64 },
    ]);
    expect(result.violations).toEqual([]);
    const report = formatContextBridgeSizeReport(result);
    expect(report).toContain('AGENTS.md: 0.1 KiB (ok)');
    expect(report).toContain('WARP.md: missing');
  });

  it('reports oversized default-loaded bridge files', async () => {
    await fs.writeFile(path.join(tmpDir, 'AGENTS.md'), 'x'.repeat(32), 'utf8');
    await fs.writeFile(path.join(tmpDir, 'WARP.md'), 'x'.repeat(128), 'utf8');

    const result = await scanContextBridgeSizes({
      rootDir: tmpDir,
      ceilingBytes: 64,
      files: ['AGENTS.md', 'WARP.md'],
    });

    expect(result.violations.map((entry: { path: string }) => entry.path)).toEqual(['WARP.md']);
    expect(formatContextBridgeSizeReport(result)).toContain('Move long-form content to Tier 3');
  });

  it('enforces the bridge ceiling per file, not on the combined total', async () => {
    await fs.writeFile(path.join(tmpDir, 'AGENTS.md'), 'x'.repeat(64), 'utf8');
    await fs.writeFile(path.join(tmpDir, 'WARP.md'), 'x'.repeat(64), 'utf8');

    const result = await scanContextBridgeSizes({
      rootDir: tmpDir,
      ceilingBytes: 64,
      files: ['AGENTS.md', 'WARP.md'],
    });

    // Combined size (128 bytes) exceeds the 64-byte ceiling, but each bridge
    // file is individually within it, so there is no violation.
    expect(result.violations).toEqual([]);
  });

  it('ignores skill bodies and CLAUDE.md; labels the bridge budget', async () => {
    await fs.mkdir(path.join(tmpDir, 'skills', 'big-skill'), { recursive: true });
    await fs.writeFile(path.join(tmpDir, 'skills', 'big-skill', 'SKILL.md'), 'x'.repeat(100_000), 'utf8');
    await fs.writeFile(path.join(tmpDir, 'CLAUDE.md'), 'x'.repeat(100_000), 'utf8');

    // Neither an on-demand skill body (runtime reattachment budget) nor
    // CLAUDE.md (aggregate startup-context scan) is a bridge file, so a
    // bridge-only scan stays clean despite 200KB of non-bridge content.
    const result = await scanContextBridgeSizes({
      rootDir: tmpDir,
      ceilingBytes: 64,
      files: ['AGENTS.md', 'WARP.md'],
    });

    expect(result.violations).toEqual([]);

    await fs.writeFile(path.join(tmpDir, 'AGENTS.md'), 'x'.repeat(128), 'utf8');
    const over = await scanContextBridgeSizes({
      rootDir: tmpDir,
      ceilingBytes: 64,
      files: ['AGENTS.md', 'WARP.md'],
    });
    const report = formatContextBridgeSizeReport(over);
    expect(report).toContain('per file');
    expect(report).toContain('not the startup skill listing');
    expect(report).toContain('bridge-bytes budget');
  });
});
