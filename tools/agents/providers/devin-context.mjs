/**
 * Transform command content into a Devin skill (SKILL.md with name/description
 * frontmatter). Devin 3.x has no commands or workflows surface — skills are
 * the only invocable format it loads.
 */
/**
 * Deploy commands as native skills for Devin and its deprecated Windsurf alias.
 */
export function deployWorkflows(commandFiles, targetDir, opts) {
  const { dryRun } = opts;
  const layout = layoutFor(opts);
  const destDir = path.join(targetDir, layout.commandsDest);

  if (!dryRun) {
    ensureDir(destDir);
  }

  console.log(`\nDeploying ${commandFiles.length} commands as Devin skills to ${destDir}...`);

  for (const cmdFile of commandFiles) {
    const content = fs.readFileSync(cmdFile, 'utf8');

    const skillName = path.basename(cmdFile, '.md');
    const skillDir = path.join(destDir, skillName);
    const destFile = path.join(skillDir, 'SKILL.md');
    const skillContent = addManagedMarker(transformCommandToSkill(cmdFile, content, opts));

    if (dryRun) {
      console.log(`[dry-run] deploy command skill: ${skillName}/SKILL.md`);
    } else {
      ensureDir(skillDir);
      fs.writeFileSync(destFile, skillContent, 'utf8');
      fs.writeFileSync(path.join(skillDir, '.aiwg-managed'), 'aiwg\n', 'utf8');
      console.log(`deployed command skill: ${skillName}/SKILL.md`);
    }
  }
}

const AIWG_MCP_SERVER = { command: 'aiwg', args: ['mcp', 'serve'] };

/**
 * Ensure .devin/mcp_config.json exists with the AIWG MCP server registered.
 * Merge-only: existing mcpServers entries and unrelated keys are preserved.
 */
export function ensureDevinMcpConfig(target, opts) {
  const configPath = path.join(target, '.devin', 'mcp_config.json');
  if (opts.dryRun) {
    console.log('[dry-run] Would write .devin/mcp_config.json (project MCP config)');
    return;
  }

  let existing = {};
  if (fs.existsSync(configPath)) {
    existing = JSON.parse(fs.readFileSync(configPath, 'utf8'));
    if (!existing || typeof existing !== 'object' || Array.isArray(existing)) {
      throw new Error('Devin MCP config must contain a JSON object: ' + configPath);
    }
  }

  const mcpServers = { ...(existing.mcpServers || {}) };
  if (!mcpServers.aiwg) {
    mcpServers.aiwg = AIWG_MCP_SERVER;
  }
  const merged = { ...existing, mcpServers };
  ensureDir(path.dirname(configPath));
  writeContextFileSync(configPath, `${JSON.stringify(merged, null, 2)}\n`, 'utf8');
  console.log('Created .devin/mcp_config.json (project MCP config)');
}

