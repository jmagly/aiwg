// Generate Devin startup context and native command skills.
import fs from 'node:fs';
import path from 'node:path';
import { ensureDir, deployFiles, addManagedMarker } from './base.mjs';
import { writeContextFileSync } from './context-write.mjs';
import { paths } from './windsurf.mjs';
import { transformAgent, transformCommandToSkill } from './devin-transforms.mjs';
const layoutFor = () => ({ paths, commandsDest: '.devin/skills/' });
export function generateAgentsMd(files, destPath, opts) {
  if (opts.contextFiles === false) return;
  // Keep definitions in the discrete agent directory; the rules index routes
  // invocation so the shared startup file stays a bootstrap/core/hook surface.
  const target = path.dirname(destPath);
  const dir = path.join(target, layoutFor(opts).paths.agents);
  ensureDir(dir, opts.dryRun);
  deployFiles(files, dir, opts, transformAgent);
  if (!opts.dryRun && !fs.existsSync(destPath)) writeContextFileSync(destPath, '<!-- aiwg-managed -->\n');
  return files.length;
}

